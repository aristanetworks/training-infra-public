def get_device_abbreviation(device_type: str) -> str:
    """
    Get the 2-letter abbreviation for a device type.

    This is the expected abbreviation that parse_device_name() will generate.

    Args:
        device_type: Device type name (e.g., 'borderleaf')

    Returns:
        2-letter abbreviation (e.g., 'bo')
    """
    return device_type[:2].lower()


def is_legacy_abbreviation(abbrev: str) -> bool:
    """
    Check if an abbreviation is a legacy format (not generated by nodebuilder).

    Legacy abbreviations like 'bl', 'gw', 'fw' are supported for parsing
    but are never generated by nodebuilder.

    Args:
        abbrev: 2-letter abbreviation

    Returns:
        True if this is a legacy abbreviation
    """
    legacy = {'bl', 'gw', 'fw'}
    return abbrev.lower() in legacy


def get_abbreviation_mapping() -> Dict[str, str]:
    """
    Get a copy of the device abbreviation mapping.

    Useful for other services that need to display device type mappings.

    Returns:
        Copy of DEVICE_ABBREVIATIONS dict
    """
    return DEVICE_ABBREVIATIONS.copy()
