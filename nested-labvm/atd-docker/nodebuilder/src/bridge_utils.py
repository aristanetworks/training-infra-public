def split_device_port(part: str) -> Tuple[str, str]:
    """
    Split a device+port string into (device_code, port_code).

    Handles multiple formats:
    1. 'x' separator: 'le5x1' -> ('le5', '1'), 'fi1xet1' -> ('fi1', 'et1')
    2. 'eth' prefix: 'client1eth1' -> ('client1', 'eth1')
    3. 'et' prefix: 'sp1et1' -> ('sp1', 'et1')
    4. Full names: 'leaf3Et3' -> ('leaf3', 'Et3')
    5. Legacy kvmbuilder: 'le11' -> ('le1', '1')

    Args:
        part: Combined device+port string

    Returns:
        Tuple of (device_code, port_code)
    """
    lower = part.lower()

    # Check for 'x' separator (nodebuilder format)
    # The separator 'x' should have a digit before it and:
    # - digit after (e.g., le5x1)
    # - 'e' after (e.g., fi1xet1 for eth port)
    # - 'w' after (e.g., ve1xwa1 for VeloCloud WAN)
    # - 'l' after (e.g., ve1xla1 for VeloCloud LAN)
    # - 't' after (e.g., vc1xtr1 for VeloCloud Gateway transport)
    for i, c in enumerate(lower):
        if c == 'x' and i > 0 and i < len(part) - 1:
            prev_char = lower[i - 1]
            next_char = lower[i + 1]
            if prev_char.isdigit() and (next_char.isdigit() or next_char in 'ewlt'):
                return part[:i], part[i + 1:]

    # Look for 'eth' (longer prefix, for Linux hosts)
    eth_idx = lower.find('eth')
    if eth_idx > 0:
        return part[:eth_idx], part[eth_idx:]

    # Look for 'et' (for Ethernet)
    et_idx = lower.find('et')
    if et_idx > 0:
        return part[:et_idx], part[et_idx:]

    # Legacy kvmbuilder format: {1-or-2-letter-prefix}{device-num}{port-num}
    # e.g., 'le11' = prefix 'le', device '1', port '1'
    # e.g., 'a11' = prefix 'a', device '1', port '1' (L4 topology: A1, P3, etc.)
    match = re.match(r'^([a-zA-Z]{1,2})(\d)(\d+)$', part)
    if match:
        prefix = match.group(1)
        device_num = match.group(2)
        port_num = match.group(3).lstrip('0') or '0'
        return f"{prefix}{device_num}", port_num

    # Fallback: return whole part as device with empty port
    return part, ""


def expand_device_code(code: str) -> str:
    """
    Expand abbreviated device code to full device name.

    Uses DEVICE_ABBREVIATIONS for lookup.

    Examples:
        le5 -> leaf5
        sp4 -> spine4
        fi1 -> firewall1
        bo1 -> borderleaf1

    Args:
        code: Abbreviated device code (e.g., 'le5')

    Returns:
        Full device name (e.g., 'leaf5')
    """
    if not code:
        return code

    # Extract prefix and number
    prefix = ''
    number = ''
    for char in code:
        if char.isalpha():
            prefix += char
        elif char.isdigit():
            number += char

    # Look up the full name
    prefix_lower = prefix.lower()
    if prefix_lower in DEVICE_ABBREVIATIONS:
        full_prefix = DEVICE_ABBREVIATIONS[prefix_lower]
        return f"{full_prefix}{number}"

    # If not found in mapping, return as-is (might already be full name)
    return code


def expand_port_code(code: str) -> str:
    """
    Expand abbreviated port code to full port name.

    Examples:
        1 -> Ethernet1
        et5 -> Ethernet5
        eth1 -> eth1 (Linux host interface, keep as-is)
        wa1 -> wan1 (VeloCloud WAN port)
        la1 -> lan1 (VeloCloud LAN port)

    Known limitation: 'et0' expands to 'Ethernet0' even if original was 'eth0'.
    This is because we can't distinguish between abbreviated Ethernet and
    abbreviated eth (Linux interface) in the bridge name.

    Args:
        code: Abbreviated port code

    Returns:
        Full port name
    """
    if not code:
        return code

    code_lower = code.lower()

    # Linux host interface - keep as-is
    if code_lower.startswith('eth'):
        return code

    # Full VeloCloud port names - keep as-is
    if code_lower.startswith('wan') or code_lower.startswith('lan'):
        return code

    # Abbreviated VeloCloud WAN port: wa1 -> wan1
    if code_lower.startswith('wa') and len(code) >= 3:
        number = ''.join(c for c in code if c.isdigit())
        if number:
            return f"wan{number}"
        return code

    # Abbreviated VeloCloud LAN port: la1 -> lan1
    if code_lower.startswith('la') and len(code) >= 3:
        number = ''.join(c for c in code if c.isdigit())
        if number:
            return f"lan{number}"
        return code

    # Abbreviated VeloCloud Gateway transport port: tr1 -> transport1
    if code_lower.startswith('tr') and len(code) >= 3:
        number = ''.join(c for c in code if c.isdigit())
        if number:
            return f"transport{number}"
        return code

    # Ethernet abbreviation: et5 -> Ethernet5
    if code_lower.startswith('et'):
        number = ''.join(c for c in code if c.isdigit())
        if number:
            return f"Ethernet{number}"
        return code

    # Just a number: 1 -> Ethernet1
    if code.isdigit():
        return f"Ethernet{code}"

    # Default: return as-is
    return code


def parse_bridge_name(bridge_name: str) -> Dict:
    """
    Parse bridge name to extract device/port information.

    This is the reverse of generate_bridge_name(), allowing display of
    friendly device and port names from the bridge name.

    Handles both formats:
    - Nodebuilder format: le5x1-sp4x9 (with 'x' separator)
    - Legacy kvmbuilder format: le11-sp41 (no separator)

    Args:
        bridge_name: OVS bridge name (e.g., 'le5x1-sp4x9')

    Returns:
        Dict with:
            source_device: Abbreviated source device code (e.g., 'le5')
            source_port: Abbreviated source port code (e.g., '1')
            source_device_name: Full source device name (e.g., 'leaf5')
            source_port_name: Full source port name (e.g., 'Ethernet1')
            target_device: Abbreviated target device code (e.g., 'sp4')
            target_port: Abbreviated target port code (e.g., '9')
            target_device_name: Full target device name (e.g., 'spine4')
            target_port_name: Full target port name (e.g., 'Ethernet9')
    """
    result = {
        "source_device": "",
        "source_port": "",
        "source_device_name": "",
        "source_port_name": "",
        "target_device": "",
        "target_port": "",
        "target_device_name": "",
        "target_port_name": ""
    }

    if '-' not in bridge_name:
        return result

    try:
        parts = bridge_name.split('-')
        if len(parts) >= 2:
            src = parts[0]
            tgt = parts[1]

            # Parse each part
            src_device, src_port = split_device_port(src)
            tgt_device, tgt_port = split_device_port(tgt)

            # Store abbreviated codes
            result["source_device"] = src_device
            result["source_port"] = src_port
            result["target_device"] = tgt_device
            result["target_port"] = tgt_port

            # Expand to full names for display
            result["source_device_name"] = expand_device_code(src_device)
            result["source_port_name"] = expand_port_code(src_port)
            result["target_device_name"] = expand_device_code(tgt_device)
            result["target_port_name"] = expand_port_code(tgt_port)

    except Exception as e:
        logger.warning(f"Parse error for bridge {bridge_name}: {e}")

    return result


