"""
Bridge Utilities - Single Source of Truth for Bridge Naming

This module provides the canonical implementation for:
- Device name abbreviation (for bridge name generation)
- Bridge name generation (OVS bridge naming convention)
- Bridge name parsing (reverse lookup for display)

All other modules should import from here to ensure consistency
between bridge generation and parsing across services.

Bridge Name Format (nodebuilder convention):
    {dev1_code}x{port1_code}-{dev2_code}x{port2_code}
    Example: le5x1-sp4x9 (leaf5 Ethernet1 to spine4 Ethernet9)

Device Abbreviations:
    First 2 letters of device type + device number
    Examples: spine1 -> sp1, borderleaf1 -> bo1, firewall1 -> fi1
"""

import hashlib
import logging
import re
from typing import Dict, Optional, Tuple

logger = logging.getLogger('nodebuilder.bridge_utils')


# =============================================================================
# DEVICE ABBREVIATIONS - Single Source of Truth
# =============================================================================
# Used by both generation (device_name -> code) and parsing (code -> device_name)
#
# Generation: First 2 letters of device type (e.g., borderleaf -> bo)
# Parsing: Look up abbreviation to expand to full name (e.g., bo -> borderleaf)
#
# IMPORTANT: When adding new device types:
# 1. Add the 2-letter abbreviation here
# 2. The abbreviation MUST be the first 2 letters of the device type
# 3. This ensures parse_device_name() generates matching codes

DEVICE_ABBREVIATIONS = {
    # Fabric devices
    'sp': 'spine',
    'le': 'leaf',
    'bo': 'borderleaf',    # First 2 letters, NOT 'bl'
    'me': 'memleaf',

    # Edge/routing devices
    'fi': 'firewall',      # First 2 letters, NOT 'fw'
    'ga': 'gateway',       # First 2 letters, NOT 'gw'
    'ro': 'router',
    'co': 'core',
    'pe': 'pe',
    'ce': 'ce',
    'dc': 'dci',
    'rr': 'rr',

    # Endpoints
    'ho': 'host',
    'cl': 'client',
    'cu': 'customer',
    'oo': 'oob',

    # VeloCloud devices
    've': 'vce',           # VeloCloud Edge
    'vc': 'vcg',           # VeloCloud Gateway
    'vo': 'vco',           # VeloCloud Orchestrator

    # Provider/external
    'is': 'isp',
    'in': 'internet',

    # Legacy abbreviations (for parsing old bridges only)
    # These are NOT generated by nodebuilder, but may exist in old topologies
    'bl': 'borderleaf',    # Legacy: some old bridges use 'bl'
    'gw': 'gateway',       # Legacy: some old bridges use 'gw'
    'fw': 'firewall',      # Legacy: some old bridges use 'fw'
}


