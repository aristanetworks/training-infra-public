def parse_device_name(dev_name: str) -> Dict:
    """
    Parse a device name into a short code for bridge naming.

    Uses first 2 letters of device type + device number.
    This ensures consistency with DEVICE_ABBREVIATIONS for round-trip parsing.

    Examples:
        spine1 -> sp1
        leaf1 -> le1
        borderleaf1 -> bo1
        firewall1 -> fi1 (NOT fw1)
        gateway1 -> ga1 (NOT gw1)
        Ethernet3 -> 3 (just the number for ports)
        eth1 -> eth1 (Linux host interface, preserved)
        host1 -> ho1
        wan1 -> wa1 (VeloCloud WAN port)
        lan1 -> la1 (VeloCloud LAN port)

    Args:
        dev_name: Device or port name

    Returns:
        Dict with 'name' (original) and 'code' (short code)
    """
    alpha = ''
    numer = ''
    split_len = 2
    dev_dc = False
    dev_core = False
    tmp_dev_name = ""

    # Handle DC suffix (e.g., spine1-dc1)
    if '-dc' in dev_name.lower() and 'dci' not in dev_name.lower():
        _tmp = dev_name.split('-')
        tmp_dev_name = _tmp[0]
        if len(_tmp) > 1 and 'dc' in _tmp[1].lower():
            dev_dc = _tmp[1]
        for char in tmp_dev_name:
            if char.isalpha():
                alpha += char
            elif char.isdigit():
                numer += char
    # Handle CORE suffix (e.g., leaf1-core)
    elif '-core' in dev_name.lower():
        _tmp = dev_name.split('-')
        tmp_dev_name = _tmp[0]
        if len(_tmp) > 1:
            dev_core = _tmp[1]
        for char in tmp_dev_name:
            if char.isalpha():
                alpha += char
            elif char.isdigit():
                numer += char
    else:
        for char in dev_name:
            if char.isalpha():
                alpha += char
            elif char.isdigit():
                numer += char

    # For Ethernet ports, just use the number
    if 'ethernet' in dev_name.lower():
        dev_short = ''
    # For Linux eth ports (eth1, eth2), preserve 'eth' prefix
    elif dev_name.lower().startswith('eth') and len(alpha) == 3:
        dev_short = 'eth'
    else:
        dev_short = alpha[:split_len].lower()

    # Handle DC/CORE codes
    if dev_dc:
        dev_code = dev_dc.lower().replace('c', '')
    elif dev_core:
        dev_code = dev_core.lower().replace('ore', '')
    else:
        dev_code = ""

    return {
        'name': dev_name,
        'code': dev_short + numer + dev_code,
    }


def generate_bridge_name(
    device1: str,
    port1: str,
    device2: str,
    port2: str
) -> str:
    """
    Generate OVS bridge name following nodebuilder conventions.

    Format: {dev1_code}x{port1_code}-{dev2_code}x{port2_code}
    Example: le5x1-sp4x9 (leaf5 Ethernet1 to spine4 Ethernet9)

    The 'x' separator allows reliable parsing to extract device and port codes.

    Note: Device names are normalized to lowercase to ensure consistent
    bridge names regardless of input case (Spine1 vs spine1).

    Bridge names are limited to 15 characters (OVS/Linux interface limit).
    If the generated name exceeds this, it will be truncated with a hash suffix
    to maintain uniqueness.

    Args:
        device1: First device name
        port1: First port name
        device2: Second device name
        port2: Second port name

    Returns:
        Bridge name string (always lowercase, max 15 chars)
    """
    # Normalize to lowercase for consistent bridge names
    dev1_info = parse_device_name(device1.lower())
    port1_info = parse_device_name(port1.lower())
    dev2_info = parse_device_name(device2.lower())
    port2_info = parse_device_name(port2.lower())

    # Use 'x' as separator between device code and port code for better parsing
    # Format: {dev1_code}x{port1_code}-{dev2_code}x{port2_code}
    bridge_name = (
        f"{dev1_info['code']}x{port1_info['code']}-"
        f"{dev2_info['code']}x{port2_info['code']}"
    )

    # OVS/Linux has 15 char limit for interface names
    MAX_BRIDGE_LEN = 15
    if len(bridge_name) > MAX_BRIDGE_LEN:
        # Truncate and add hash suffix for uniqueness
        full_name = bridge_name
        hash_suffix = hashlib.md5(full_name.encode()).hexdigest()[:4]
        bridge_name = bridge_name[:MAX_BRIDGE_LEN - 5] + '-' + hash_suffix
        logger.debug(f"Bridge name truncated: {full_name} -> {bridge_name}")

    return bridge_name


def generate_interface_target_name(vm_name: str, suffix: str) -> str:
    """
    Generate a safe interface target name for libvirt VM definitions.

    Linux interface names are limited to 15 characters (IFNAMSIZ - 1).
    This function ensures the generated name fits within that limit.

    Format: {shortened_vm_name}_{suffix}
    If too long, truncates vm_name and adds hash for uniqueness.

    Examples:
        ('leaf1', 'mgmt') -> 'leaf1_mgmt' (10 chars, OK)
        ('orchestrator1', 'mgmt') -> 'orch1_m_a1b2' (12 chars, truncated)
        ('edge1', 'transport1') -> 'edge1_t1' (8 chars, OK)

    Args:
        vm_name: Name of the VM
        suffix: Interface suffix (e.g., 'mgmt', 'eth1', 'transport1')

    Returns:
        Interface target name (max 15 chars)
    """
    MAX_IFACE_LEN = 15

    # Shorten common suffixes
    suffix_map = {
        'mgmt': 'm',
        'management': 'm',
        'transport1': 't1',
        'transport2': 't2',
        'ethernet1': 'e1',
        'ethernet2': 'e2',
        'ethernet3': 'e3',
        'ethernet4': 'e4',
        'ethernet5': 'e5',
        'ethernet6': 'e6',
        'ethernet7': 'e7',
        'ethernet8': 'e8',
    }

    short_suffix = suffix_map.get(suffix.lower(), suffix.lower())

    # Try full name first
    full_name = f"{vm_name}_{short_suffix}"

    if len(full_name) <= MAX_IFACE_LEN:
        return full_name

    # Need to truncate - use first part of vm_name + hash + suffix
    # Format: {truncated_name}_{suffix}_{hash}
    # Reserve space for: underscore + suffix + underscore + 4-char hash
    hash_suffix = hashlib.md5(full_name.encode()).hexdigest()[:4]
    suffix_part = f"_{short_suffix}_{hash_suffix}"
    available_for_name = MAX_IFACE_LEN - len(suffix_part)

    if available_for_name < 2:
        # Extreme case - just use hash
        return f"vm_{hash_suffix}"

    truncated_name = vm_name[:available_for_name]
    result = f"{truncated_name}{suffix_part}"

    logger.debug(f"Interface target truncated: {full_name} -> {result}")
    return result


